-- 飞猫配送业务数据库初始化脚本（仅建表，不创建默认账号或演示数据）
CREATE DATABASE IF NOT EXISTS axcx DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE axcx;

CREATE TABLE IF NOT EXISTS fm_driver (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    mobile VARCHAR(20) DEFAULT NULL,
    password VARCHAR(100) DEFAULT NULL,
    name VARCHAR(50) DEFAULT NULL,
    avatar VARCHAR(255) DEFAULT NULL,
    id_card VARCHAR(20) DEFAULT NULL,
    driver_license VARCHAR(50) DEFAULT NULL,
    vehicle_license VARCHAR(50) DEFAULT NULL,
    plate_number VARCHAR(20) DEFAULT NULL,
    vehicle_type VARCHAR(50) DEFAULT NULL,
    auth_status TINYINT DEFAULT 0,
    status TINYINT DEFAULT 1,
    online_status TINYINT DEFAULT 0,
    balance DECIMAL(10,2) DEFAULT 0.00,
    openid VARCHAR(100) DEFAULT NULL,
    deleted TINYINT DEFAULT 0,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_mobile (mobile)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fm_staff (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    staff_no VARCHAR(50) DEFAULT NULL,
    mobile VARCHAR(20) NOT NULL,
    password VARCHAR(100) NOT NULL,
    name VARCHAR(50) DEFAULT NULL,
    avatar VARCHAR(255) DEFAULT NULL,
    role TINYINT DEFAULT 1,
    status TINYINT DEFAULT 1,
    deleted TINYINT DEFAULT 0,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_mobile (mobile),
    UNIQUE KEY uk_staff_no (staff_no)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fm_customer (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    name VARCHAR(100) DEFAULT NULL,
    mobile VARCHAR(20) DEFAULT NULL,
    address VARCHAR(255) DEFAULT NULL,
    contact VARCHAR(50) DEFAULT NULL,
    deleted TINYINT DEFAULT 0,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fm_orders (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    order_no VARCHAR(50) NOT NULL,
    customer_id BIGINT UNSIGNED DEFAULT NULL,
    driver_id BIGINT UNSIGNED DEFAULT NULL,
    staff_id BIGINT UNSIGNED DEFAULT NULL,
    start_address VARCHAR(255) DEFAULT NULL,
    start_lng DECIMAL(10,6) DEFAULT NULL,
    start_lat DECIMAL(10,6) DEFAULT NULL,
    end_address VARCHAR(255) DEFAULT NULL,
    end_lng DECIMAL(10,6) DEFAULT NULL,
    end_lat DECIMAL(10,6) DEFAULT NULL,
    goods_name VARCHAR(100) DEFAULT NULL,
    goods_weight DECIMAL(10,2) DEFAULT NULL,
    goods_volume DECIMAL(10,2) DEFAULT NULL,
    freight DECIMAL(10,2) DEFAULT NULL,
    actual_freight DECIMAL(10,2) DEFAULT NULL,
    distance DECIMAL(10,2) DEFAULT NULL,
    status TINYINT DEFAULT 0,
    pay_status TINYINT DEFAULT 0,
    remark VARCHAR(500) DEFAULT NULL,
    accept_time DATETIME DEFAULT NULL,
    start_time DATETIME DEFAULT NULL,
    arrive_time DATETIME DEFAULT NULL,
    complete_time DATETIME DEFAULT NULL,
    deleted TINYINT DEFAULT 0,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_order_no (order_no),
    KEY idx_driver (driver_id),
    KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fm_driver_balance_log (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    driver_id BIGINT UNSIGNED NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    type TINYINT DEFAULT 1,
    order_id BIGINT UNSIGNED DEFAULT NULL,
    remark VARCHAR(255) DEFAULT NULL,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    KEY idx_driver (driver_id),
    UNIQUE KEY uk_driver_order_income (driver_id, order_id, type)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS fm_withdraw (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    driver_id BIGINT UNSIGNED NOT NULL,
    amount DECIMAL(10,2) NOT NULL,
    status TINYINT DEFAULT 0,
    reject_reason VARCHAR(255) DEFAULT NULL,
    transfer_batch_id VARCHAR(100) DEFAULT NULL,
    review_note VARCHAR(255) DEFAULT NULL,
    review_time DATETIME DEFAULT NULL,
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_driver (driver_id),
    KEY idx_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
